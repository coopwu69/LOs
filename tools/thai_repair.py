# Remove the "correct" entries that shouldn't be changed
_REPAIRS_CLEAN = {k: v for k, v in REPAIRS.items() if k != v}


def repair(text: str) -> tuple[str, list[str]]:
    """Repair broken Thai text. Returns (fixed_text, list_of_replacements)."""
    if not text:
        return text, []

    # NFC normalization first
    text = unicodedata.normalize("NFC", text)

    replacements = []
    for bad, good in _REPAIRS_CLEAN.items():
        if bad in text:
            count = text.count(bad)
            text = text.replace(bad, good)
            replacements.append(f'"{bad}" -> "{good}" (x{count})')

    # Collapse whitespace
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = text.strip()

    return text, replacements


